'use strict';
const assert=require('node:assert/strict');
process.chdir(__dirname);
const fs=require('node:fs');
const vm=require('node:vm');
const M=require('./dist/exterior-model.js');
const ctx={window:{}};
vm.runInNewContext(fs.readFileSync('./dist/exterior-locations.js','utf8'),ctx);
const loc=ctx.window.EXTERIOR_LOCATIONS;
assert.equal(loc.length,186);
assert.equal(new Set(loc.map(x=>x.code)).size,186);
assert(loc.every(x=>/^\d{5}$/.test(x.code)&&x.country&&x.name));
const conf=JSON.parse(fs.readFileSync('./municipios-tse.json','utf8'));
const official=conf.abr.find(a=>a.cd==='zz').mu;
assert.deepEqual([...loc.map(x=>x.code)].sort(),[...official.map(x=>x.cd)].sort());
const grouping=M.group(loc,{});
assert.equal(grouping.localities,186);
assert(grouping.countries>90);
const d=JSON.parse(fs.readFileSync('./data-first-turn/zz.json','utf8'));
const before=JSON.parse(JSON.stringify(d));
before.tpabr='mu';before.cdabr=loc[0].code;
const one=M.readResult(before,'6257',loc[0].code);
assert.equal(one.valid,330882);
assert.equal(one.a,157387);
assert.equal(one.b,143900);
assert.equal(one.other,29595);
assert.equal(one.pending,false);
assert.throws(()=>M.readResult(before,'6258',loc[0].code),/turno diferente/);
assert.throws(()=>M.readResult(before,'6257',loc[1].code),/localidade/);
const many={};
for(const x of loc)many[x.code]={code:x.code,a:0,b:0,other:0,valid:0,counted:1,sections:1,pending:false};
many[loc[0].code]={...one};
const groups=M.group(loc,many);
assert.equal(groups.total.loaded,186);
assert.equal(groups.total.valid,330882);
assert.equal(groups.total.a,157387);
assert.equal(groups.total.b,143900);
assert(M.compare(groups.total,{a:157387,b:143900,other:29595,valid:330882}).matches);
assert(!M.compare(groups.total,{a:157386,b:143900,other:29595,valid:330882}).matches);
const partial={...many};delete partial[loc[10].code];
assert.equal(M.group(loc,partial).total.loaded,185);
assert.throws(()=>M.group(loc,{...many,99999:one}),/desconhecida/);
assert.throws(()=>M.group(loc,{...many,[loc[1].code]:{...many[loc[1].code],valid:5}}),/inconsistentes/);
console.log('Exterior: 186 localidades reconhecidas, normalização EA20, primeiro turno, agrupamento, cobertura e reconciliação aprovados.');
